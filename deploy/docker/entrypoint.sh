#!/usr/bin/env bash
# OpenKIS container entrypoint.
#  1. installs / upgrades the code in the web root volume from the image copy
#     (/usr/src/openkis), keeping everything the framework generated at run
#     time (misc/, .htaccess, sections created from the admin area, ...)
#  2. writes extra/openkis_config.local.php from the environment
#  3. creates the api_keys.local.js files from the examples / environment
#  4. waits for the database and starts the install wizard on a fresh volume
set -euo pipefail

WEBROOT=/var/www/html
SRC=/usr/src/openkis
say() { echo "[openkis] $*"; }

: "${OPENKIS_DB_HOST:=db}"
: "${OPENKIS_DB_NAME:=openkis}"
: "${OPENKIS_DB_USER:=openkis}"
: "${OPENKIS_DB_PASSWORD:=}"
: "${OPENKIS_CUSTOM:=}"
: "${OPENKIS_MCP_APIKEY:=}"
: "${OPENKIS_MCP_USER:=admin}"
: "${OPENKIS_MCP_READONLY:=0}"
: "${OPENKIS_DB_WAIT:=60}"
: "${OPENKIS_DB_INDEXES:=1}"
: "${OPENKIS_DB_INDEXES_INTERVAL:=3600}"
: "${OPENKIS_DISPLAY_ERRORS:=off}"
: "${OPENKIS_ENABLE_PROXY:=0}"

# php single-quoted string literal
phpq() { printf "'%s'" "$(printf '%s' "$1" | sed -e "s/\\\\/\\\\\\\\/g" -e "s/'/\\\\'/g")"; }
jsq() { phpq "$1"; }

# --- 1. code -----------------------------------------------------------------
IMAGE_VERSION=$(cat "$SRC/.openkis-image-version" 2>/dev/null || echo unknown)
INSTALLED_VERSION=$(cat "$WEBROOT/.openkis-image-version" 2>/dev/null || echo none)
if [ "$IMAGE_VERSION" != "$INSTALLED_VERSION" ]; then
    say "installing code version $IMAGE_VERSION (volume had: $INSTALLED_VERSION)"
    # no --delete: files created by the framework or the admin stay in place
    rsync -a --chown=www-data:www-data \
        --exclude '/misc/' \
        --exclude '/extra/openkis_config.local.php' \
        --exclude '/config.vars.local.php' \
        --exclude '/bs_map/conf/api_keys.local.js' \
        --exclude '/themes/api_keys.local.js' \
        "$SRC/" "$WEBROOT/"
fi

# --- 2. configuration ----------------------------------------------------------
CONF="$WEBROOT/extra/openkis_config.local.php"
MARKER="generated by the openkis container entrypoint"
if [ ! -f "$CONF" ] || grep -q "$MARKER" "$CONF"; then
    say "writing extra/openkis_config.local.php from the environment"
    {
        echo "<?php"
        echo "// $MARKER: edit the .env file, not this file."
        echo "// Remove this line to manage the file by hand (it will then be left untouched)."
        echo "global \$_FN;"
        echo "\$_FN['default_database_driver'] = 'mysql';"
        echo "\$_FN['xmetadb_mysqlhost'] = $(phpq "$OPENKIS_DB_HOST");"
        echo "\$_FN['xmetadb_mysqldatabase'] = $(phpq "$OPENKIS_DB_NAME");"
        echo "\$_FN['xmetadb_mysqlusername'] = $(phpq "$OPENKIS_DB_USER");"
        echo "\$_FN['xmetadb_mysqlpassword'] = $(phpq "$OPENKIS_DB_PASSWORD");"
        echo "\$_FN['openkis_custom'] = $(phpq "$OPENKIS_CUSTOM");"
        if [ -n "$OPENKIS_MCP_APIKEY" ]; then
            echo "\$_FN['openkis_mcp_apikey'] = $(phpq "$OPENKIS_MCP_APIKEY");"
            echo "\$_FN['openkis_mcp_user'] = $(phpq "$OPENKIS_MCP_USER");"
            echo "\$_FN['openkis_mcp_readonly'] = $(( OPENKIS_MCP_READONLY ? 1 : 0 ));"
        fi
        echo "if (!empty(\$_FN['openkis_custom']))"
        echo "{"
        echo "    FN_IncludeScript(\"extra/openkis/custom/{\$_FN['openkis_custom']}/{\$_FN['openkis_custom']}.php\");"
        echo "}"
    } > "$CONF"
    chown www-data:www-data "$CONF"
    chmod 640 "$CONF"
else
    say "extra/openkis_config.local.php is managed by hand, left untouched"
fi
# finis framework settings, read before the OpenKIS config. display_errors is
# "on" by default in finis: PHP warnings would end up inside KML/JSON exports.
{
    echo "<?php"
    echo "// generated by the openkis container entrypoint (OPENKIS_DISPLAY_ERRORS)"
    echo "global \$_FN;"
    echo "\$_FN['display_errors'] = $(phpq "$OPENKIS_DISPLAY_ERRORS");"
} > "$WEBROOT/config.vars.local.php"
chown www-data:www-data "$WEBROOT/config.vars.local.php"

if [ -n "$OPENKIS_CUSTOM" ] && [ ! -f "$WEBROOT/extra/openkis/custom/$OPENKIS_CUSTOM/$OPENKIS_CUSTOM.php" ]; then
    say "WARNING: OPENKIS_CUSTOM=$OPENKIS_CUSTOM but extra/openkis/custom/$OPENKIS_CUSTOM/ does not exist"
fi

# openkis_proxy.php forwards any URL from the server (SSRF). Only the
# Lombardia map layers use it (IGM WMS), so it is off unless asked for.
if [ "$OPENKIS_ENABLE_PROXY" = 1 ]; then
    rm -f /etc/apache2/conf-enabled/openkis-proxy.conf
    say "WARNING: openkis_proxy.php enabled (open HTTP proxy for anyone who can reach the site)"
else
    printf '<LocationMatch "^/+openkis_proxy\\.php">\n    Require all denied\n</LocationMatch>\n' \
        > /etc/apache2/conf-enabled/openkis-proxy.conf
fi

# --- 3. map api keys -----------------------------------------------------------
# Regenerated on every start when a key is given in the environment,
# otherwise created once from the example and then left alone.
if [ -n "${THUNDERFOREST_API_KEY:-}${MAPTILER_API_KEY:-}${ALGOLIA_DOCSEARCH_API_KEY:-}" ] \
   || [ ! -f "$WEBROOT/bs_map/conf/api_keys.local.js" ]; then
    cat > "$WEBROOT/bs_map/conf/api_keys.local.js" <<EOF
// generated by the openkis container entrypoint from the environment
var API_KEYS = {
    THUNDERFOREST: $(jsq "${THUNDERFOREST_API_KEY:-}"),
    MAPTILER: $(jsq "${MAPTILER_API_KEY:-}"),
    ALGOLIA_DOCSEARCH: $(jsq "${ALGOLIA_DOCSEARCH_API_KEY:-}")
};
EOF
fi
if [ -n "${ALGOLIA_DOCSEARCH_API_KEY:-}" ] || [ ! -f "$WEBROOT/themes/api_keys.local.js" ]; then
    cat > "$WEBROOT/themes/api_keys.local.js" <<EOF
// generated by the openkis container entrypoint from the environment
var THEME_API_KEYS = {
    ALGOLIA_DOCSEARCH: $(jsq "${ALGOLIA_DOCSEARCH_API_KEY:-}")
};
EOF
fi

# --- 4. database + first install -----------------------------------------------
say "waiting for MySQL at $OPENKIS_DB_HOST (up to ${OPENKIS_DB_WAIT}s)"
for i in $(seq 1 "$OPENKIS_DB_WAIT"); do
    if mariadb-admin ping -h "$OPENKIS_DB_HOST" -u "$OPENKIS_DB_USER" --password="$OPENKIS_DB_PASSWORD" --skip-ssl --silent 2>/dev/null; then
        say "database is up"
        break
    fi
    [ "$i" = "$OPENKIS_DB_WAIT" ] && say "WARNING: database not reachable, starting anyway"
    sleep 1
done

if [ ! -d "$WEBROOT/misc/fndatabase" ]; then
    mkdir -p "$WEBROOT/misc"
    touch "$WEBROOT/misc/firstinstall"
    say "fresh installation: open the site to run the setup wizard"
fi

# --- 5. database indexes ----------------------------------------------------------
# sql/openkis_indexes.sql adds the secondary indexes (see INDEXES.md). It is
# idempotent and skips tables that don't exist yet; OpenKIS creates tables on
# first use, so it runs now and then again every OPENKIS_DB_INDEXES_INTERVAL
# seconds (0 = only at start), in the background so Apache is not delayed.
INDEXES_SQL="$SRC/sql/openkis_indexes.sql"
db_sql() {
    mariadb -h "$OPENKIS_DB_HOST" -u "$OPENKIS_DB_USER" --password="$OPENKIS_DB_PASSWORD" \
        --skip-ssl -N "$OPENKIS_DB_NAME" "$@"
}
count_indexes() {
    db_sql -e "SELECT COUNT(DISTINCT table_name, index_name) FROM information_schema.statistics
               WHERE table_schema = DATABASE() AND index_name LIKE 'okx\\_%'" 2>/dev/null || echo 0
}
if [ "$OPENKIS_DB_INDEXES" = "1" ] && [ -f "$INDEXES_SQL" ]; then
    (
        first=1
        while :; do
            before=$(count_indexes)
            if db_sql < "$INDEXES_SQL" 2>/tmp/openkis-indexes.err; then
                after=$(count_indexes)
                if [ "$after" != "$before" ] || [ "$first" = 1 ]; then
                    say "database indexes: $after in place ($((after - before)) added)"
                fi
                first=0
            else
                say "WARNING: database index script failed: $(tr '\n' ' ' < /tmp/openkis-indexes.err)"
            fi
            [ "$OPENKIS_DB_INDEXES_INTERVAL" -gt 0 ] 2>/dev/null || break
            sleep "$OPENKIS_DB_INDEXES_INTERVAL"
        done
    ) &
fi

echo "$IMAGE_VERSION" > "$WEBROOT/.openkis-image-version"
chown www-data:www-data "$WEBROOT" "$WEBROOT/misc" "$WEBROOT/misc/firstinstall" \
    "$WEBROOT/.openkis-image-version" "$WEBROOT/bs_map/conf/api_keys.local.js" \
    "$WEBROOT/themes/api_keys.local.js" 2>/dev/null || true

# a pid file left by the previous run (docker restart, host reboot) makes
# apache2ctl exit with "httpd (pid N) already running" when N is now another
# process of this container, and the container restarts forever
rm -f "${APACHE_PID_FILE:-/var/run/apache2/apache2.pid}"

exec "$@"
